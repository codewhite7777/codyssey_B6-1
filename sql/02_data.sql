-- 행 수 (과제: 각 테이블 10행 이상)
--   category 10 / member 10 / book 12 / rental 15
--
-- 일부러 섞은 데이터 (쿼리 결과가 의미 있게 나오도록)
--   | 섞은 데이터                 | 어떤 행                         | 확인할 쿼리                      |
--   |-----------------------------|---------------------------------|----------------------------------|
--   | 책이 한 권도 없는 카테고리  | 9 시집, 10 요리                 | category LEFT JOIN book          |
--   | 한 번도 안 빌린 회원        | 3 박민수, 9 한서윤              | member LEFT JOIN rental, 서브쿼리 |
--   | 한 번도 안 빌린 책          | 9 국부론, 11 하루 한 줄 에세이  | book LEFT JOIN rental            |
--   | 아직 반납 안 한 대여        | rental 12~15 (returned_at NULL) | 대여 중 조회, UPDATE 반납 처리   |
--   | 많이 빌린 회원과 책         | 회원 1 김철수 4회, 책 1 4회     | GROUP BY 인기 순위               |
--   | 가격 5,000 ~ 25,000원       | book 전체                       | WHERE 범위, 정렬, SUM/AVG        |
--   | 제목에 같은 단어            | book 1, 2 "해리포터"            | LIKE 검색                        |
--   | 대여일 9월 ~ 10월           | rental 전체                     | 날짜 정렬, 최근 대여             |
--   | 전화번호 없는 회원          | 8 임도현, 10 오지훈             | phone NULL 허용                  |
--
-- 쓰기 규칙
--   - 부모 먼저: category → member → book → rental
--   - 날짜는 'YYYY-MM-DD' 글자, 반납일은 대여일보다 뒤
